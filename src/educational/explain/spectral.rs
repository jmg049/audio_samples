    #[test]
    fn empty_mel_bands_match_the_real_filterbank() {
        // Impulse with a rectangular window: flat unit spectrum, so a mel band
        // is zero exactly when its filter contains no bin.
        let (fs, n_fft, n_mels) = (16_000u32, 256usize, 128usize);
        let mut data = vec![0.0f64; n_fft];
        data[0] = 1.0;
        let audio = AudioSamples::<f64>::from_mono_vec(
            non_empty_slice::NonEmptyVec::new(data).unwrap(),
            std::num::NonZeroU32::new(fs).unwrap(),
        );
        let stft = StftParams::new(
            NonZeroUsize::new(n_fft).unwrap(),
            NonZeroUsize::new(n_fft).unwrap(),
            WindowType::Rectangular,
            false,
        )
        .unwrap();
        let sp = SpectrogramParams::new(stft, f64::from(fs)).unwrap();
        let mel = MelParams::new(NonZeroUsize::new(n_mels).unwrap(), 0.0, 8000.0).unwrap();
        let spec = audio.mel_power_spectrogram(&sp, &mel).unwrap();
        let zero_rows = spec
            .data()
            .rows()
            .into_iter()
            .filter(|r| r.iter().all(|v| *v == 0.0))
            .count();
        let doc = mel.explain_with(
            &ExplainContext::new()
                .with_sample_rate(f64::from(fs))
                .with_n_fft(n_fft),
        );
        assert!(zero_rows > 0);
        assert_eq!(
            doc.quantity("Empty filters").unwrap().value as usize,
            zero_rows
        );
        assert!(doc.has_warning(WarningLevel::Caution));
        // A coarse filterbank has no empty bands.
        let mel40 = MelParams::new(nzu!(40), 0.0, 8000.0).unwrap();
        let d = mel40.explain_with(
            &ExplainContext::new()
                .with_sample_rate(16_000.0)
                .with_n_fft(1024),
        );
        assert_eq!(d.quantity("Empty filters").unwrap().value, 0.0);
        // f_max above Nyquist.
        let d = mel40.explain_with(&ExplainContext::new().with_sample_rate(8_000.0));
        assert!(d.has_warning(WarningLevel::Problem));
    }

