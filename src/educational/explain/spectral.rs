//! Explanations for the spectral-analysis configuration types re-used from
//! the `spectrograms` crate: [`WindowType`], [`StftParams`],
//! [`SpectrogramParams`], [`MelParams`] and [`MfccParams`].
//!
//! Every figure is derived from the same code paths the transforms use:
//! window coefficients come from [`spectrograms::make_window`], the frame
//! count reproduces the STFT planner's framing rule (and is tested against a
//! real `stft()` call), and the mel band edges use the Slaney mel scale that
//! the `spectrograms` filterbank implements.

use std::num::NonZeroUsize;

use spectrograms::{
    MelNorm, MelParams, MfccParams, SpectrogramParams, StftParams, WindowType, make_window,
};

use super::doc::{ExplainDoc, Table, Topic, WarningLevel, fmt_num};
use super::numeric::{WindowMetrics, overlap_check, window_metrics};
use super::{Explain, ExplainContext, note_missing_sample_rate};

/// Window length used when nothing else determines it.
const DEFAULT_WINDOW_LEN: usize = 1024;

/// Display name and LaTeX definition (as generated by `make_window`).
fn window_formula(window: &WindowType) -> (String, Option<&'static str>) {
    match window {
        WindowType::Rectangular => ("Rectangular".into(), Some(r"w[n] = 1")),
        WindowType::Hanning => (
            "Hann".into(),
            Some(r"w[n] = 0.5 - 0.5 \cos\left(\frac{2 \pi n}{N-1}\right)"),
        ),
        WindowType::Hamming => (
            "Hamming".into(),
            Some(r"w[n] = 0.54 - 0.46 \cos\left(\frac{2 \pi n}{N-1}\right)"),
        ),
        WindowType::Blackman => (
            "Blackman".into(),
            Some(
                r"w[n] = 0.42 - 0.5 \cos\left(\frac{2 \pi n}{N-1}\right) + 0.08 \cos\left(\frac{4 \pi n}{N-1}\right)",
            ),
        ),
        WindowType::Kaiser { beta } => (
            format!("Kaiser (β = {})", fmt_num(*beta)),
            Some(
                r"w[n] = \frac{I_0\left(\beta \sqrt{1 - \left(\frac{2n}{N-1} - 1\right)^2}\right)}{I_0(\beta)}",
            ),
        ),
        WindowType::Gaussian { std } => (
            format!("Gaussian (σ = {} samples)", fmt_num(*std)),
            Some(r"w[n] = \exp\left(-\frac{1}{2}\left(\frac{n - (N-1)/2}{\sigma}\right)^2\right)"),
        ),
        WindowType::Custom { .. } => ("Custom".into(), None),
        _ => ("Window".into(), None),
    }
}

/// Generates the coefficients exactly as the STFT does.
fn coefficients(window: &WindowType, n: NonZeroUsize) -> Vec<f64> {
    make_window::<f64>(window.clone(), n)
        .iter()
        .copied()
        .collect()
}

/// Adds the measured window figures (in bins, and in Hz when `fs` is known).
fn add_window_quantities(doc: &mut ExplainDoc, m: &WindowMetrics, fs: Option<f64>) {
    let n = m.n as f64;
    doc.add_quantity(
        "Coherent gain",
        "CG",
        m.coherent_gain,
        "",
        r"\frac{1}{N}\sum_n w[n]",
    )
    .add_quantity(
        "Coherent gain (dB)",
        r"20\log_{10} CG",
        20.0 * m.coherent_gain.log10(),
        "dB",
        r"20 \log_{10} CG",
    )
    .add_quantity(
        "Equivalent noise bandwidth",
        "ENBW",
        m.enbw_bins,
        "bins",
        r"N \sum_n w^2[n] / (\sum_n w[n])^2",
    )
    .add_quantity(
        "Scalloping loss",
        "L_s",
        m.scalloping_loss_db,
        "dB",
        r"-20\log_{10} |W(\tfrac{1}{2}\,\mathrm{bin})| / |W(0)|",
    );
    if let Some(psl) = m.peak_side_lobe_db {
        doc.add_quantity(
            "Peak side-lobe level",
            "PSL",
            psl,
            "dB",
            r"\max_{f > f_{null}} 20\log_{10}|W(f)/W(0)|",
        );
    }
    if let Some(w3) = m.width_3db_bins {
        doc.add_quantity(
            "Main-lobe width (-3 dB)",
            r"B_{3}",
            w3,
            "bins",
            r"|W(B_3/2)|^2 = \tfrac{1}{2}|W(0)|^2",
        );
    }
    if let Some(w6) = m.width_6db_bins {
        doc.add_quantity(
            "Main-lobe width (-6 dB)",
            r"B_{6}",
            w6,
            "bins",
            r"|W(B_6/2)| = \tfrac{1}{2}|W(0)|",
        );
    }
    if let Some(null) = m.first_null_bins {
        doc.add_quantity(
            "First null",
            r"f_{null}",
            null,
            "bins",
            r"\text{first minimum of } |W(f)|",
        );
    }
    if let Some(fs) = fs {
        let bin = fs / n;
        doc.add_quantity(
            "Window duration",
            r"N / f_s",
            1000.0 * n / fs,
            "ms",
            r"1000 N / f_s",
        )
        .add_quantity(
            "ENBW (Hz)",
            r"\mathrm{ENBW} \cdot f_s/N",
            m.enbw_bins * bin,
            "Hz",
            r"\mathrm{ENBW} \cdot f_s / N",
        );
        if let Some(w6) = m.width_6db_bins {
            doc.add_quantity(
                "Main-lobe width (-6 dB, Hz)",
                r"B_{6} f_s/N",
                w6 * bin,
                "Hz",
                r"B_6 \cdot f_s / N",
            );
        }
    }
}

/// Builds the explanation of `window` at length `n` (shared by
/// [`topics::window`](super::topics::window) and the [`Explain`] impl).
pub(crate) fn explain_window(window: &WindowType, n: usize, fs: Option<f64>) -> ExplainDoc {
    let (name, formula) = window_formula(window);
    let mut doc = ExplainDoc::new(Topic::Windowing, format!("{name} window"));
    let n = match window {
        WindowType::Custom { size, .. } if size.get() != n => {
            doc.add_warning(
                WarningLevel::Info,
                format!("This custom window has {} coefficients; it is analysed at that length, not {n}.", size.get()),
                "",
            );
            size.get()
        }
        _ => n,
    };
    let Some(n_nz) = NonZeroUsize::new(n) else {
        doc.add_warning(
            WarningLevel::Problem,
            "The window length must be at least 1.",
            "",
        );
        return doc;
    };
    let w = coefficients(window, n_nz);
    let m = window_metrics(&w);
    if let Some(f) = formula {
        doc.add_formula(f, "Window coefficients as generated (n = 0, …, N-1)");
    }
    doc.add_formula(
        r"\mathrm{CG} = \frac{1}{N}\sum_{n=0}^{N-1} w[n]",
        "Coherent gain: amplitude of a bin-centred tone relative to a rectangular window",
    )
    .add_formula(
        r"\mathrm{ENBW} = \frac{N \sum_{n} w^2[n]}{\left(\sum_{n} w[n]\right)^2}",
        "Equivalent noise bandwidth in bins: how much broadband noise each bin collects",
    )
    .add_formula(
        r"W(f) = \sum_{n=0}^{N-1} w[n] \, e^{-j \frac{2\pi}{N} f n}",
        "Window spectrum (f in bins), measured on a zero-padded FFT",
    );
    doc.add_symbol_value("N", "window length", n.to_string(), "samples")
        .add_symbol("w[n]", "window coefficient");
    if let WindowType::Kaiser { beta } = window {
        doc.add_symbol_value(r"\beta", "Kaiser shape parameter", fmt_num(*beta), "");
    }
    if let WindowType::Gaussian { std } = window {
        doc.add_symbol_value(r"\sigma", "Gaussian width", fmt_num(*std), "samples");
    }
    add_window_quantities(&mut doc, &m, fs);
    doc.set_summary(format!(
        "A {n}-point {name} window. Its main lobe is {} bins wide at -6 dB and its highest side lobe sits at {} dB; \
         each bin collects noise from {} bins' worth of bandwidth.",
        m.width_6db_bins.map_or_else(|| "?".into(), fmt_num),
        m.peak_side_lobe_db.map_or_else(|| "?".into(), fmt_num),
        fmt_num(m.enbw_bins)
    ));
    doc.add_trade_off("A wider main lobe (poorer frequency resolution) buys lower side lobes (less leakage from strong components into weak ones).")
        .add_trade_off("Higher ENBW means more noise per bin; low coherent gain means smaller peak values, which amplitude-calibrated plots must correct for.");
    let constant = w.iter().all(|v| (v - w[0]).abs() <= 1e-12);
    if m.symmetric && n > 1 && !constant {
        doc.add_warning(
            WarningLevel::Info,
            "The generated window is symmetric (w[n] = w[N-1-n], denominator N-1), not periodic (DFT-even, denominator N).",
            "Symmetric windows suit filter design; periodic ones tile exactly under overlap-add. The STFT explanation reports the measured overlap-add ripple.",
        );
    } else if m.periodic {
        doc.add_warning(
            WarningLevel::Info,
            "The window is periodic (DFT-even): w[n] = w[N-n].",
            "",
        );
    }
    doc.add_see_also("Coefficients", "spectrograms::make_window")
        .add_see_also(
            "Apply to a signal",
            "audio_samples::AudioProcessing::apply_window",
        )
        .add_see_also("Python", "audio_samples.explain.window");
    doc
}

impl Explain for WindowType {
    /// Explains the window at length `ctx.n_fft` (default 1024, or the
    /// custom window's own length).
    fn explain_with(&self, ctx: &ExplainContext) -> ExplainDoc {
        let (n, defaulted) = match (self, ctx.n_fft) {
            (_, Some(n)) => (n, false),
            (WindowType::Custom { size, .. }, None) => (size.get(), false),
            (_, None) => (DEFAULT_WINDOW_LEN, true),
        };
        let mut doc = explain_window(self, n, ctx.valid_sample_rate());
        if defaulted {
            doc.add_warning(
                WarningLevel::Info,
                format!("No window length given; figures are for N = {DEFAULT_WINDOW_LEN}. In bins they barely depend on N."),
                "Use ExplainContext::with_n_fft to choose the length.",
            );
        }
        doc
    }
}

/// Number of STFT frames for `n_samples` samples, reproducing the
/// `spectrograms` planner: with `centre`, the signal is padded with
/// `⌊N/2⌋` zeros on both sides; at least one frame is always produced.
pub(crate) fn stft_frame_count(n_samples: usize, n_fft: usize, hop: usize, centre: bool) -> usize {
    let pad = if centre { n_fft / 2 } else { 0 };
    let padded = n_samples + 2 * pad;
    if padded < n_fft {
        1
    } else {
        (padded - n_fft) / hop + 1
    }
}

impl Explain for StftParams {
    fn explain_with(&self, ctx: &ExplainContext) -> ExplainDoc {
        let n = self.n_fft().get();
        let hop = self.hop_size().get();
        let centre = self.centre();
        let window = self.window();
        let (wname, _) = window_formula(&window);
        let w = coefficients(&window, self.n_fft());
        let m = window_metrics(&w);
        let ola = overlap_check(&w, hop);
        let fs = ctx.valid_sample_rate();
        let pad = if centre { n / 2 } else { 0 };
        let overlap_pct = 100.0 * (1.0 - hop as f64 / n as f64);

        let mut doc = ExplainDoc::new(Topic::Stft, "Short-time Fourier transform (STFT)");
        doc.add_formula(
            r"X_m[k] = \sum_{n=0}^{N-1} x[mH + n - p] \, w[n] \, e^{-j \frac{2\pi}{N} k n}",
            "Frame m: window N samples starting at mH - p and take an N-point DFT (samples outside the signal are 0)",
        )
        .add_formula(
            r"M = \left\lfloor \frac{L + 2p - N}{H} \right\rfloor + 1",
            "Number of frames for L samples (at least 1)",
        )
        .add_formula(r"\Delta f = \frac{f_s}{N}, \quad \Delta t = \frac{H}{f_s}", "Bin spacing and frame period")
        .add_formula(
            r"\hat{x}[n] = \frac{\sum_m w[n - mH] \, y_m[n - mH]}{\sum_m w^2[n - mH]}",
            "Inverse STFT as implemented (weighted overlap-add): exact wherever the denominator is non-zero (NOLA)",
        );
        doc.add_symbol_value("N", "FFT and window length", n.to_string(), "samples")
            .add_symbol_value("H", "hop size", hop.to_string(), "samples")
            .add_symbol_value("p", if centre { "padding (centre = true): ⌊N/2⌋ zeros each side" } else { "padding (centre = false)" }, pad.to_string(), "samples")
            .add_symbol_value("w[n]", "analysis window", wname.clone(), "")
            .add_symbol("m", "frame index; frame m is time-stamped t_m = mH/f_s (its centre when centre = true, its start otherwise)")
            .add_symbol("L", "signal length in samples");
        if let Some(fs) = fs {
            doc.add_symbol_value("f_s", "sample rate", fmt_num(fs), "Hz");
        }

        doc.add_quantity(
            "Frequency bins",
            r"\lfloor N/2 \rfloor + 1",
            (n / 2 + 1) as f64,
            "",
            r"\lfloor N/2 \rfloor + 1",
        )
        .add_quantity("Overlap", r"1 - H/N", overlap_pct, "%", r"100 (1 - H/N)");
        if let Some(fs) = fs {
            doc.add_quantity(
                "Frequency resolution",
                r"\Delta f",
                fs / n as f64,
                "Hz",
                r"f_s / N",
            )
            .add_quantity(
                "Frame period",
                r"\Delta t",
                1000.0 * hop as f64 / fs,
                "ms",
                r"1000 H / f_s",
            )
            .add_quantity(
                "Window duration",
                r"N / f_s",
                1000.0 * n as f64 / fs,
                "ms",
                r"1000 N / f_s",
            )
            .add_quantity(
                "Frame rate",
                r"f_s / H",
                fs / hop as f64,
                "frames/s",
                r"f_s / H",
            )
            .add_quantity(
                "Effective noise bandwidth",
                r"\mathrm{ENBW}\,\Delta f",
                m.enbw_bins * fs / n as f64,
                "Hz",
                r"\mathrm{ENBW} \cdot f_s / N",
            );
            if let Some(w6) = m.width_6db_bins {
                doc.add_quantity(
                    "Main-lobe width (-6 dB)",
                    r"B_6 \Delta f",
                    w6 * fs / n as f64,
                    "Hz",
                    r"B_6 \cdot f_s / N",
                );
            }
        } else {
            note_missing_sample_rate(&mut doc);
        }
        if let Some(l) = ctx.n_samples {
            let frames = stft_frame_count(l, n, hop, centre);
            doc.add_quantity(
                "Frames",
                "M",
                frames as f64,
                "",
                r"\lfloor (L + 2p - N)/H \rfloor + 1",
            )
            .add_quantity(
                "Output size (values)",
                r"M(\lfloor N/2 \rfloor + 1)",
                (frames * (n / 2 + 1)) as f64,
                "complex values",
                r"M (\lfloor N/2 \rfloor + 1)",
            );
            if l + 2 * pad < n {
                doc.add_warning(
                    WarningLevel::Info,
                    format!("The signal ({l} samples) is shorter than one frame even after padding; a single, mostly zero frame is produced."),
                    "",
                );
            }
        }
        doc.add_quantity(
            "Overlap-add gain",
            r"C_{OLA}",
            ola.cola_mean,
            "",
            r"\mathrm{mean}_n \sum_m w[n - mH]",
        )
        .add_quantity(
            "Overlap-add ripple",
            r"\mathrm{COLA}",
            ola.cola_ripple,
            "",
            r"\frac{\max - \min}{\mathrm{mean}} \sum_m w[n - mH]",
        )
        .add_quantity(
            "Minimum squared-window sum",
            r"\min_n \sum_m w^2[n-mH]",
            ola.nola_min,
            "",
            r"\min_n \sum_m w^2[n - mH]",
        );

        doc.set_summary(format!(
            "Frames of {n} samples ({wname} window) every {hop} samples ({}% overlap){}. Each frame gives {} frequency bins{}.",
            fmt_num(overlap_pct),
            if centre { ", centred by padding ⌊N/2⌋ zeros at both ends" } else { ", starting at sample 0 without padding" },
            n / 2 + 1,
            fs.map_or_else(String::new, |fs| format!(
                " spaced {} Hz apart, one frame every {} ms",
                fmt_num(fs / n as f64),
                fmt_num(1000.0 * hop as f64 / fs)
            ))
        ));
        doc.add_trade_off("A longer window sharpens frequency resolution (Δf = f_s/N) but blurs timing; you cannot have both (time-frequency uncertainty).")
            .add_trade_off("A smaller hop gives smoother tracks over time at proportionally more computation; it does not improve frequency resolution.")
            .add_trade_off("The window shape trades main-lobe width (resolution) against side-lobe level (leakage); see the window explanation.");

        // Warnings computed from the parameters.
        if ola.nola_min <= 1e-10 {
            doc.add_warning(
                WarningLevel::Problem,
                "Some samples receive (almost) zero total window weight, so istft cannot reconstruct them (NOLA fails).",
                "Reduce the hop or use a window that is non-zero where frames overlap.",
            );
        }
        if ola.cola_ripple > 1e-9 {
            doc.add_warning(
                WarningLevel::Info,
                format!(
                    "The window/hop pair is not constant-overlap-add: the summed windows ripple by {}% around their mean.",
                    fmt_num(100.0 * ola.cola_ripple)
                ),
                "Plain overlap-add would modulate the amplitude; this crate's istft divides by the summed squared windows, so reconstruction stays exact where NOLA holds.",
            );
        }
        if !centre && w.first().is_some_and(|v| v.abs() < 1e-5) {
            doc.add_warning(
                WarningLevel::Info,
                format!(
                    "Without centring, the first {} samples are covered by fewer frames and sample 0 only by frame 0, where w[0] ≈ 0; istft cannot recover it.",
                    n.saturating_sub(hop)
                ),
                "Use centre = true when you need to invert the transform.",
            );
        }
        if !n.is_power_of_two() {
            doc.add_warning(
                WarningLevel::Info,
                format!("N = {n} is not a power of two; mixed-radix FFTs handle it, but prime-heavy sizes are slower."),
                format!("The nearest power of two is {}.", n.next_power_of_two()),
            );
        }
        if let (Some(fs), Some((f0_lo, _))) = (fs, ctx.f0_range_hz) {
            if f0_lo > 0.0 {
                let window_s = n as f64 / fs;
                if window_s < 2.0 / f0_lo {
                    doc.add_warning(
                        WarningLevel::Caution,
                        format!(
                            "The window ({} ms) is shorter than two periods of the lowest expected f0 ({} Hz needs {} ms), so its harmonics will not form clear peaks.",
                            fmt_num(1000.0 * window_s),
                            fmt_num(f0_lo),
                            fmt_num(2000.0 / f0_lo)
                        ),
                        format!("Use N ≥ {} samples at this sample rate.", (2.0 * fs / f0_lo).ceil()),
                    );
                }
                let df = fs / n as f64;
                if df > f0_lo {
                    doc.add_warning(
                        WarningLevel::Caution,
                        format!(
                            "The bin spacing ({} Hz) is coarser than the lowest expected f0 ({} Hz), so adjacent harmonics fall into the same bin.",
                            fmt_num(df),
                            fmt_num(f0_lo)
                        ),
                        m.width_6db_bins.map_or_else(String::new, |w6| format!(
                            "Resolving harmonics needs the main lobe (≈ {} bins = {} Hz wide here) narrower than f0.",
                            fmt_num(w6),
                            fmt_num(w6 * df)
                        )),
                    );
                }
            }
        }
        doc.add_see_also("Forward transform", "audio_samples::AudioTransforms::stft")
            .add_see_also("Inverse transform", "audio_samples::AudioTransforms::istft")
            .add_see_also(
                "Window figures",
                "audio_samples::educational::topics::window",
            )
            .add_see_also("Python", "audio_samples.explain.explain(StftParams)");
        doc
    }
}

