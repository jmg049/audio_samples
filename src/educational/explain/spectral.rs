/// Slaney mel scale, as implemented by the `spectrograms` filterbank
/// (linear below 1 kHz, logarithmic above; librosa's `htk=False`).
pub(crate) fn hz_to_mel_slaney(hz: f64) -> f64 {
    let f_sp = 200.0 / 3.0;
    let log_step = 6.4f64.ln() / 27.0;
    if hz >= 1000.0 {
        1000.0 / f_sp + (hz / 1000.0).ln() / log_step
    } else {
        hz / f_sp
    }
}

/// Inverse of [`hz_to_mel_slaney`].
pub(crate) fn mel_to_hz_slaney(mel: f64) -> f64 {
    let f_sp = 200.0 / 3.0;
    let log_step = 6.4f64.ln() / 27.0;
    let min_log_mel = 1000.0 / f_sp;
    if mel >= min_log_mel {
        1000.0 * (log_step * (mel - min_log_mel)).exp()
    } else {
        f_sp * mel
    }
}

/// Band edge frequencies `f_0 … f_{M+1}` of a mel filterbank, in Hz.
fn mel_edges(n_mels: usize, f_min: f64, f_max: f64) -> Vec<f64> {
    let (lo, hi) = (hz_to_mel_slaney(f_min), hz_to_mel_slaney(f_max));
    let step = (hi - lo) / (n_mels + 1) as f64;
    (0..n_mels + 2)
        .map(|i| mel_to_hz_slaney(lo + i as f64 * step))
        .collect()
}

/// Indices of filters that receive no FFT bin (all weights zero), using the
/// same triangle rule as the `spectrograms` filterbank.
pub(crate) fn empty_mel_filters(edges: &[f64], n_fft: usize, fs: f64) -> Vec<usize> {
    let df = fs / n_fft as f64;
    let bins = n_fft / 2 + 1;
    (0..edges.len() - 2)
        .filter(|&m| {
            let (l, c, r) = (edges[m], edges[m + 1], edges[m + 2]);
            if c - l == 0.0 || r - c == 0.0 {
                return true;
            }
            !(0..bins).any(|k| {
                let f = k as f64 * df;
                ((f - l) / (c - l)).min((r - f) / (r - c)).clamp(0.0, 1.0) > 0.0
            })
        })
        .collect()
}

impl Explain for MelParams {
    /// Uses `ctx.sample_rate_hz` (Nyquist check) and `ctx.n_fft` (empty-band
    /// check).
    fn explain_with(&self, ctx: &ExplainContext) -> ExplainDoc {
        let n_mels = self.n_mels().get();
        let (f_min, f_max) = (self.f_min(), self.f_max());
        let edges = mel_edges(n_mels, f_min, f_max);
        let mut doc = ExplainDoc::new(Topic::Mel, "Mel filterbank");
        doc.add_formula(
            r"m(f) = \begin{cases} \frac{3f}{200} & f < 1000 \\ 15 + \frac{27 \ln(f/1000)}{\ln 6.4} & f \geq 1000 \end{cases}",
            "Slaney mel scale, as implemented (linear below 1 kHz, logarithmic above; librosa's htk=False). The HTK form 2595 log10(1 + f/700) is not used",
        )
        .add_formula(
            r"f_i = m^{-1}\left(m(f_{min}) + i \, \frac{m(f_{max}) - m(f_{min})}{M + 1}\right), \quad i = 0, \dots, M+1",
            "Band edges: M + 2 points equally spaced on the mel scale",
        )
        .add_formula(
            r"H_i(f) = \max\left(0, \min\left(\frac{f - f_{i-1}}{f_i - f_{i-1}}, \frac{f_{i+1} - f}{f_{i+1} - f_i}\right)\right)",
            "Triangular filter i evaluated at each FFT bin frequency (peak 1)",
        );
        let norm_text = match self.norm() {
            MelNorm::None => {
                "None: triangles keep peak 1, so wide high-frequency bands collect more energy"
            }
            MelNorm::Slaney => {
                "Slaney: each triangle is scaled by 2/(f_{i+1} - f_{i-1}) (Hz), giving equal area"
            }
            MelNorm::L1 => "L1: each filter's weights are scaled to sum to 1",
            MelNorm::L2 => "L2: each filter's weights are scaled to unit Euclidean norm",
            _ => "other",
        };
        if self.norm() == MelNorm::Slaney {
            doc.add_formula(
                r"\tilde{H}_i = \frac{2}{f_{i+1} - f_{i-1}} H_i",
                "Slaney area normalisation",
            );
        }
        doc.add_symbol_value("M", "number of mel bands", n_mels.to_string(), "")
            .add_symbol_value(r"f_{min}", "lowest edge", fmt_num(f_min), "Hz")
            .add_symbol_value(r"f_{max}", "highest edge", fmt_num(f_max), "Hz")
            .add_symbol_value("norm", "filter normalisation", norm_text, "");
        let mel_lo = hz_to_mel_slaney(f_min);
        let mel_hi = hz_to_mel_slaney(f_max);
        let width = |i: usize| edges[i + 2] - edges[i];
        doc.add_quantity(
            "Mel range",
            r"m(f_{max}) - m(f_{min})",
            mel_hi - mel_lo,
            "mel",
            r"m(f_{max}) - m(f_{min})",
        )
        .add_quantity(
            "Mel spacing",
            r"\Delta m",
            (mel_hi - mel_lo) / (n_mels + 1) as f64,
            "mel",
            r"(m(f_{max}) - m(f_{min}))/(M+1)",
        )
        .add_quantity(
            "Lowest band centre",
            r"f_1",
            edges[1],
            "Hz",
            r"m^{-1}(m(f_{min}) + \Delta m)",
        )
        .add_quantity(
            "Highest band centre",
            r"f_M",
            edges[n_mels],
            "Hz",
            r"m^{-1}(m(f_{max}) - \Delta m)",
        )
        .add_quantity(
            "Narrowest band width",
            r"f_2 - f_0",
            width(0),
            "Hz",
            r"f_{i+1} - f_{i-1}",
        )
        .add_quantity(
            "Widest band width",
            r"f_{M+1} - f_{M-1}",
            width(n_mels - 1),
            "Hz",
            r"f_{i+1} - f_{i-1}",
        );
        let mut rows = Vec::new();
        let shown: Vec<usize> = if n_mels <= 6 {
            (0..n_mels).collect()
        } else {
            vec![0, 1, 2, n_mels - 3, n_mels - 2, n_mels - 1]
        };
        for i in shown {
            rows.push(vec![
                (i + 1).to_string(),
                fmt_num(edges[i]),
                fmt_num(edges[i + 1]),
                fmt_num(edges[i + 2]),
                fmt_num(width(i)),
            ]);
        }
        doc.add_table(Table {
            caption: "Band edges (lowest and highest bands)".into(),
            headers: vec![
                "Band".into(),
                "Lower (Hz)".into(),
                "Centre (Hz)".into(),
                "Upper (Hz)".into(),
                "Width (Hz)".into(),
            ],
            rows,
        });
        doc.set_summary(format!(
            "{n_mels} triangular filters spaced evenly on the Slaney mel scale between {} Hz and {} Hz; bands are \
             {} Hz wide at the bottom and {} Hz wide at the top. Normalisation: {:?}.",
            fmt_num(f_min),
            fmt_num(f_max),
            fmt_num(width(0)),
            fmt_num(width(n_mels - 1)),
            self.norm()
        ));
        doc.add_trade_off("More mel bands give finer spectral detail but narrower low-frequency bands, which may contain no FFT bin.")
            .add_trade_off("Mel spacing mimics the ear: roughly linear resolution below 1 kHz and logarithmic above.");
        match ctx.valid_sample_rate() {
            Some(fs) => {
                let nyq = fs / 2.0;
                if f_max > nyq {
                    doc.add_warning(
                        WarningLevel::Problem,
                        format!("f_max = {} Hz is above the Nyquist frequency ({} Hz); the filterbank construction rejects this.", fmt_num(f_max), fmt_num(nyq)),
                        format!("Set f_max ≤ {} Hz.", fmt_num(nyq)),
                    );
                }
                match ctx.n_fft {
                    Some(n_fft) if n_fft > 0 => {
                        let df = fs / n_fft as f64;
                        doc.add_quantity("FFT bin spacing", r"\Delta f", df, "Hz", r"f_s / N");
                        let empty = empty_mel_filters(&edges, n_fft, fs);
                        doc.add_quantity(
                            "Empty filters",
                            r"M_{empty}",
                            empty.len() as f64,
                            "",
                            r"\#\{i : H_i(k f_s/N) = 0 \ \forall k\}",
                        );
                        if !empty.is_empty() {
                            doc.add_warning(
                                WarningLevel::Caution,
                                format!(
                                    "{} of {n_mels} mel filters contain no FFT bin (bin spacing {} Hz, narrowest band {} Hz); those bands are always zero.",
                                    empty.len(),
                                    fmt_num(df),
                                    fmt_num(width(0))
                                ),
                                "Use fewer mel bands, raise f_min, or a larger n_fft.",
                            );
                        } else if edges[1] - edges[0] < df {
                            doc.add_warning(
                                WarningLevel::Info,
                                format!(
                                    "The lowest filters' slopes ({} Hz) are narrower than one FFT bin ({} Hz); they are sampled by only one or two bins.",
                                    fmt_num(edges[1] - edges[0]),
                                    fmt_num(df)
                                ),
                                "",
                            );
                        }
                    }
                    _ => {
                        doc.add_warning(
                            WarningLevel::Info,
                            "No FFT size given, so empty-band checks were skipped.",
                            "Use ExplainContext::with_n_fft.",
                        );
                    }
                }
            }
            None => note_missing_sample_rate(&mut doc),
        }
        doc.add_see_also(
            "Mel spectrogram",
            "audio_samples::AudioTransforms::mel_power_spectrogram",
        )
        .add_see_also("Python", "audio_samples.explain.explain(MelParams)");
        doc
    }
}

impl Explain for MfccParams {
    /// Uses `ctx.n_mels` (the `n_mels` argument of `mfcc()`).
    fn explain_with(&self, ctx: &ExplainContext) -> ExplainDoc {
        let n_mfcc = self.n_mfcc().get();
        let lifter = self.lifter();
        let mut doc = ExplainDoc::new(Topic::Mfcc, "Mel-frequency cepstral coefficients (MFCC)");
        doc.add_formula(
            r"L_i = 10 \log_{10} \max\left(P_i, 10^{-8}\right)",
            "Log mel energies in dB with an absolute floor of -80 dB (mel filterbank 0 Hz to f_s/2, no normalisation)",
        )
        .add_formula(
            r"c_k = \sum_{i=0}^{M-1} L_i \cos\left(\frac{\pi k (i + \frac{1}{2})}{M}\right)",
            "Unnormalised DCT-II, as implemented. librosa's orthonormal DCT (norm='ortho') would return c_0/sqrt(M) and c_k·sqrt(2/M) instead",
        );
        if lifter > 0 {
            doc.add_formula(
                r"\tilde{c}_k = \left(1 + \frac{L}{2} \sin\left(\frac{\pi k}{L}\right)\right) c_k",
                "Sinusoidal liftering with k counted from 0, so c_0 keeps weight 1 (librosa counts from 1)",
            );
        }
        doc.add_symbol_value("K", "coefficients computed", n_mfcc.to_string(), "")
            .add_symbol_value("L", "lifter parameter (0 = off)", lifter.to_string(), "")
            .add_symbol("P_i", "power in mel band i");
        let n_out = if !self.include_c0() && n_mfcc > 1 {
            n_mfcc - 1
        } else {
            n_mfcc
        };
        doc.add_quantity(
            "Output coefficients per frame",
            "K_{out}",
            n_out as f64,
            "",
            r"K - [\text{c}_0 \text{ dropped}]",
        );
        if lifter > 0 {
            let weights: Vec<f64> = (0..n_mfcc)
                .map(|k| {
                    1.0 + lifter as f64 / 2.0
                        * (std::f64::consts::PI * k as f64 / lifter as f64).sin()
                })
                .collect();
            let max_w = weights.iter().copied().fold(f64::NEG_INFINITY, f64::max);
            doc.add_quantity(
                "Largest lifter weight",
                r"\max_k w_k",
                max_w,
                "",
                r"1 + (L/2)\sin(\pi k/L)",
            );
            let rows = weights
                .iter()
                .enumerate()
                .map(|(k, w)| vec![k.to_string(), fmt_num(*w)])
                .collect();
            doc.add_table(Table {
                caption: "Lifter weights".into(),
                headers: vec!["k".into(), "weight".into()],
                rows,
            });
            if weights.iter().any(|w| *w < 0.0) {
                doc.add_warning(
                    WarningLevel::Caution,
                    format!("With L = {lifter} < K = {n_mfcc}, some lifter weights are negative, flipping the sign of those coefficients."),
                    "Use L ≥ K (22 is the usual choice for 13 coefficients).",
                );
            }
        }
        doc.set_summary(format!(
            "Each frame's mel power spectrum is converted to dB, decorrelated with a DCT-II, and the first {n_mfcc} \
             coefficients are kept{}{}.",
            if lifter > 0 { format!(", liftered with L = {lifter}") } else { String::new() },
            if n_out != n_mfcc { "; c0 (overall level) is then dropped" } else { "" }
        ));
        doc.add_trade_off("Low-order coefficients describe the smooth spectral envelope (vocal-tract shape); higher ones capture finer detail and pitch harmonics.")
            .add_trade_off("Dropping c0 makes features insensitive to overall loudness.");
        if !self.include_c0() && n_mfcc == 1 {
            doc.add_warning(WarningLevel::Info, "include_c0 = false is ignored when only one coefficient is requested; c0 is returned.", "");
        } else if !self.include_c0() {
            doc.add_warning(
                WarningLevel::Info,
                format!("include_c0 = false returns {n_out} coefficients per frame, not {n_mfcc}: c0 is computed and then removed."),
                "",
            );
        }
        match ctx.n_mels {
            Some(n_mels) => {
                doc.add_symbol_value("M", "number of mel bands", n_mels.to_string(), "");
                if n_mfcc > n_mels {
                    doc.add_warning(
                        WarningLevel::Problem,
                        format!("n_mfcc = {n_mfcc} exceeds n_mels = {n_mels}; the DCT has only {n_mels} outputs and mfcc() returns an error."),
                        format!("Use n_mfcc ≤ {n_mels}."),
                    );
                }
            }
            None => {
                doc.add_symbol("M", "number of mel bands (mfcc's n_mels argument)");
                doc.add_warning(
                    WarningLevel::Info,
                    "No mel-band count given, so the n_mfcc ≤ n_mels check was skipped.",
                    "Use ExplainContext::with_n_mels.",
                );
            }
        }
        doc.add_see_also("Compute", "audio_samples::AudioTransforms::mfcc")
            .add_see_also("From log-mel", "spectrograms::mfcc_from_log_mel")
            .add_see_also("Python", "audio_samples.explain.explain(MfccParams)");
        doc
    }
}

