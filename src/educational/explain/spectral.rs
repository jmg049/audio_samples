    #[test]
    fn frame_count_matches_real_stft() {
        for &(len, n, hop, centre) in &[
            (1000usize, 256usize, 64usize, true),
            (1000, 256, 64, false),
            (4410, 1024, 256, true),
            (100, 256, 128, false),
            (100, 256, 128, true),
            (1024, 1024, 1024, false),
            (1537, 512, 300, true),
        ] {
            let audio = sine_wave::<f64>(440.0, Duration::from_secs(1), sample_rate!(44100), 0.5);
            let data: Vec<f64> = audio.as_slice().unwrap()[..len].to_vec();
            let audio = AudioSamples::<f64>::from_mono_vec(
                non_empty_slice::NonEmptyVec::new(data).unwrap(),
                sample_rate!(44100),
            );
            let params = StftParams::new(
                NonZeroUsize::new(n).unwrap(),
                NonZeroUsize::new(hop).unwrap(),
                WindowType::Hanning,
                centre,
            )
            .unwrap();
            let real = audio.stft(&params).unwrap().data.ncols();
            assert_eq!(
                stft_frame_count(len, n, hop, centre),
                real,
                "len={len} n={n} hop={hop} centre={centre}"
            );
            let doc = params.explain_with(&ExplainContext::for_audio(&audio));
            assert_eq!(doc.quantity("Frames").unwrap().value as usize, real);
        }
    }

    #[test]
    fn stft_numbers_and_warnings() {
        let p = StftParams::new(nzu!(512), nzu!(128), WindowType::Hanning, true).unwrap();
        let ctx = ExplainContext::new()
            .with_sample_rate(16_000.0)
            .with_f0_range(100.0, 300.0);
        let d = p.explain_with(&ctx);
        assert_eq!(d.quantity("Frequency resolution").unwrap().value, 31.25);
        assert_eq!(d.quantity("Frame period").unwrap().value, 8.0);
        assert_eq!(d.quantity("Window duration").unwrap().value, 32.0);
        assert_eq!(d.quantity("Overlap").unwrap().value, 75.0);
        // 32 ms ≥ 2 × 10 ms and 31.25 Hz < 100 Hz: no caution.
        assert!(!d.has_warning(WarningLevel::Caution), "{:?}", d.warnings);
        // An 80 Hz voice needs 25 ms; 256 samples at 16 kHz is 16 ms.
        let short = StftParams::new(nzu!(256), nzu!(128), WindowType::Hanning, true).unwrap();
        let d = short.explain_with(
            &ExplainContext::new()
                .with_sample_rate(16_000.0)
                .with_f0_range(80.0, 300.0),
        );
        assert!(d.has_warning_containing("shorter than two periods"));
        // Bin spacing 62.5 Hz is finer than 80 Hz: that warning does not fire.
        assert!(!d.has_warning_containing("coarser than the lowest expected f0"));
        let coarse = StftParams::new(nzu!(128), nzu!(64), WindowType::Hanning, true).unwrap();
        let d = coarse.explain_with(
            &ExplainContext::new()
                .with_sample_rate(16_000.0)
                .with_f0_range(80.0, 300.0),
        );
        assert!(d.has_warning_containing("coarser than the lowest expected f0"));
        // Non power of two.
        let odd = StftParams::new(nzu!(500), nzu!(250), WindowType::Hanning, true).unwrap();
        assert!(odd.explain().has_warning_containing("not a power of two"));
        assert!(!p.explain().has_warning_containing("not a power of two"));
    }

    #[test]
    fn cola_check_distinguishes_windows() {
        // Rectangular at hop = N/2 sums to exactly 2.
        let rect = StftParams::new(nzu!(256), nzu!(128), WindowType::Rectangular, true).unwrap();
        let d = rect.explain();
        assert!(d.quantity("Overlap-add ripple").unwrap().value < 1e-12);
        assert!(!d.has_warning_containing("not constant-overlap-add"));
        // The crate's symmetric Hann at hop = N/2 is close to, but not exactly, COLA.
        let hann = StftParams::new(nzu!(256), nzu!(128), WindowType::Hanning, true).unwrap();
        let ripple = hann.explain().quantity("Overlap-add ripple").unwrap().value;
        assert!(ripple > 1e-6 && ripple < 0.05, "{ripple}");
        // Hann with hop = N leaves gaps around the frame edges: NOLA fails.
        let gap = StftParams::new(nzu!(256), nzu!(256), WindowType::Hanning, true).unwrap();
        assert!(gap.explain().has_warning(WarningLevel::Problem));
    }

    #[test]
    fn istft_reconstruction_claim_holds() {
        // The doc claims exact reconstruction (away from the ends) whenever NOLA
        // holds, even though Hann at 50 % overlap is not exactly COLA.
        let audio = sine_wave::<f64>(440.0, Duration::from_millis(100), sample_rate!(16000), 0.5);
        let p = StftParams::new(nzu!(256), nzu!(128), WindowType::Hanning, true).unwrap();
        assert!(!p.explain().has_warning(WarningLevel::Problem));
        let rec = AudioSamples::<f64>::istft(audio.stft(&p).unwrap()).unwrap();
        let (a, b) = (audio.as_slice().unwrap(), rec.as_slice().unwrap());
        let err = a
            .iter()
            .zip(b)
            .skip(256)
            .take(a.len().min(b.len()) - 512)
            .map(|(x, y)| (x - y).abs())
            .fold(0.0, f64::max);
        assert!(err < 1e-9, "{err}");
    }

